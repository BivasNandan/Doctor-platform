import { Router } from "express";
import { requireRole } from "../middleware/authenticate.js";
import * as admin from "../controllers/admin.js";

export const adminRouter = Router();
adminRouter.use(requireRole("admin"));
adminRouter.get("/summary", admin.getSummary);
adminRouter.get("/doctors", admin.listDoctors);
adminRouter.post("/doctors", admin.createDoctor);
adminRouter.patch("/doctors/:id", admin.updateDoctor);
adminRouter.post("/doctors/:id/deactivation", admin.deactivateDoctor);
adminRouter.patch("/doctors/:id/verification", admin.setVerification);
adminRouter.patch("/doctors/:id/publication", admin.setPublication);
adminRouter.get("/clinics", admin.listClinics);
adminRouter.post("/clinics", admin.createClinic);
adminRouter.patch("/clinics/:id", admin.updateClinic);
adminRouter.post("/clinics/:id/deactivation", admin.deactivateClinic);
adminRouter.get("/specialties", admin.listSpecialties);
adminRouter.post("/specialties", admin.createSpecialty);
adminRouter.patch("/specialties/:id", admin.updateSpecialty);
adminRouter.get("/appointments", admin.listAppointments);
adminRouter.patch("/appointments/:id", admin.updateAppointmentStatus);
adminRouter.get("/availability", admin.listAvailability);
adminRouter.post("/availability", admin.createAvailability);
adminRouter.patch("/availability/:id", admin.updateAvailability);
adminRouter.delete("/availability/:id", admin.deleteAvailability);
